#!/bin/bash
# gen_man.sh — generate doc/udpspeeder-simd.1 (stdout) from the binary's own
# --help output, so the page cannot drift from the code it documents.
#
# Run through `make man` (which rebuilds the binary first). The version and
# every option line below come from the running binary; only the prose
# sections are authored here, and they carry no version numbers.

set -euo pipefail

BIN=./udpspeeder-simd
[ -x "$BIN" ] || { echo "gen_man.sh: $BIN not built; run make first" >&2; exit 1; }

version=$($BIN -h 2>/dev/null | head -1 | awk '{print $2}')
date=$(date +%Y-%m-%d)

echo ".\\\" Generated by gen_man.sh from the binary's --help; do not edit."
echo ".Dd $date"
echo ".Dt UDPSPEEDER-SIMD 1"
echo ".Os"
echo "."
echo ".Sh NAME"
echo ".Nm udpspeeder-simd"
echo ".Nd a UDP tunnel that makes a high-latency lossy link usable with Reed-Solomon redundancy"
echo "."
echo ".Sh SYNOPSIS"
echo ".Nm udpspeeder-simd"
echo ".Fl c"
echo ".Fl l Ar local_ip:local_port"
echo ".Fl r Ar server_ip:server_port"
echo ".Op Ar options"
echo ".Nm udpspeeder-simd"
echo ".Fl s"
echo ".Fl l Ar server_listen_ip:server_port"
echo ".Fl r Ar remote_ip:remote_port"
echo ".Op Ar options"
echo "."
echo ".Sh DESCRIPTION"
echo "A tunnel for high-latency, lossy links: it sends Reed-Solomon redundancy"
echo "so the far end can rebuild dropped packets. Used alone it improves UDP"
echo "flows; stacked under a UDP VPN (WireGuard, OpenVPN) it improves every"
echo "protocol the VPN carries."
echo ".Pp"
echo "This is a fork of wangyu-'s UDPspeeder; the FEC design and the tunnel"
echo "are his, and the fork adds SIMD kernels, a DNS-following endpoint,"
echo "socket marks, and measurements."
echo ".Pp"
echo "The socket marks options are validated: a mark the host cannot honor"
echo "is refused at startup."
echo ".Pp"
echo "This build identifies itself as"
echo ".Sy $version ."
echo "."
echo ".Sh OPTIONS"

# Sections and option lines from the binary's help, transformed to mdoc.
# The help prints option lines as "    -k,--key  <string>  description",
# with continuation lines indented past the option column, groups separated
# by blank lines, and group headers as lines ending in ':'.
$BIN -h 2>/dev/null | awk '
NR <= 6 { next }
/^usage:/ { next }
/run as (client|server)/ { next }
function flush_pending() { if (pending) { print ""; pending = 0 } }
/^$/ {
    flush_pending()
    if (open) { print ".El"; open = 0 }
    next
}
/^[A-Za-z].*:$/ {
    flush_pending()
    if (open) { print ".El"; open = 0 }
    header = $0; sub(/:$/, "", header)
    printf ".Ss %s\n.Bl -tag -width Ds\n", header
    open = 1
    next
}
open && /^ +-[-,A-Za-z]/ {
    flush_pending()
    line = $0
    sub(/^ +/, "", line)
    gsub(/ ,/, ",", line)                # "-j ,--jitter" -> "-j,--jitter"
    match(line, /^-[^ ]+(,-[^ ]+)?/)
    flags = substr(line, 1, RLENGTH)
    rest = substr(line, RLENGTH + 1)
    sub(/^ +/, "", rest)
    arg = ""
    if (match(rest, /^<[^>]+>/)) {
        arg = substr(rest, 1, RLENGTH)
        rest = substr(rest, RLENGTH + 1)
        sub(/^ +/, "", rest)
    }
    item = ".It "
    n = split(flags, fl, ",")
    for (i = 1; i <= n; i++) {
        p = fl[i]
        if (p ~ /^--/) item = item "Fl Fl " substr(p, 3)
        else item = item "Fl " substr(p, 2)
        if (i < n) item = item " , "
    }
    if (arg != "") item = item " Ar " substr(arg, 2, length(arg) - 2)
    print item
    printf "%s", rest
    pending = 1
    next
}
open && pending && /^ +[^- ]/ {
    line = $0
    sub(/^ +/, "", line)
    printf " %s", line
    next
}
    { flush_pending() }
END {
    flush_pending()
    if (open) print ".El"
}
'

echo "."
echo ".Sh EXAMPLES"
echo "Run a server for a UDP service on port 7777 and a client at"
echo "localhost:3333, with redundancy of 10 packets per 20:"
echo ".Bd -literal -offset indent"
echo "udpspeeder-simd -s -l0.0.0.0:4096 -r127.0.0.1:7777 -f20:10 -k passwd"
echo "udpspeeder-simd -c -l127.0.0.1:3333 -r44.55.66.77:4096 -f20:10 -k passwd"
echo ".Ed"
echo "."
echo ".Sh SEE ALSO"
echo "The documentation shipped with the source:"
echo ".Lk README.md ,"
echo ".Lk doc/vpn-over-the-tunnel.md ,"
echo ".Lk doc/socket-marks.md ,"
echo ".Lk doc/openwrt.md ,"
echo ".Lk doc/troubleshooting.md ."
echo "Upstream:"
echo ".Lk https://github.com/wangyu-/UDPspeeder ."
echo "."
echo ".Sh AUTHORS"
echo "Maintained at"
echo ".Lk https://github.com/connollydavid/UDPspeeder-simd ,"
echo "a fork of UDPspeeder by wangyu-."
echo "."
echo ".Sh LICENSE"
echo "MIT; see LICENSE.md in the source distribution."
